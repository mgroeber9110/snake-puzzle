"""Pure kinematic model of the Rubik's Snake, a port of src/kinematics.js.

The JS module is the reference; names and conventions are the same, and
tests/test_vectors.py checks this port against test/vectors.json exported from
the JS model. See src/kinematics.js for the geometry.

For speed the 24 lattice rotations are numbered once and forward kinematics
works on rotation indices with lookup tables. Angles are quarter turns 0..3,
joint j connects wedge j and j+1, all zeros is the straight stick.
"""

from __future__ import annotations

import numpy as np

NUM_WEDGES = 24
NUM_JOINTS = NUM_WEDGES - 1

IDENTITY = np.eye(3, dtype=np.int64)
# Fixed rotation from wedge j's frame to wedge j+1's frame at angle 0:
# X -> -X, Y -> -Z, Z -> -Y.
JOINT_BASE = np.array([[-1, 0, 0], [0, 0, -1], [0, -1, 0]], dtype=np.int64)


def rot_y(q: int) -> np.ndarray:
    """Rotation about the local Y axis (the joint axis) by q quarter turns."""
    c, s = [(1, 0), (0, 1), (-1, 0), (0, -1)][q % 4]
    return np.array([[c, 0, s], [0, 1, 0], [-s, 0, c]], dtype=np.int64)


def _build_tables():
    # Enumerate the rotation group generated by the joint steps.
    mats = [IDENTITY]
    index = {IDENTITY.tobytes(): 0}
    steps = [JOINT_BASE @ rot_y(a) for a in range(4)]
    frontier = [0]
    while frontier:
        nxt = []
        for r in frontier:
            for s in steps:
                m = mats[r] @ s
                k = m.tobytes()
                if k not in index:
                    index[k] = len(mats)
                    mats.append(m)
                    nxt.append(index[k])
        frontier = nxt
    n = len(mats)
    step = np.array([[index[(mats[r] @ steps[a]).tobytes()] for a in range(4)] for r in range(n)])
    exit_dir = [tuple(int(x) for x in -m[:, 2]) for m in mats]   # local -Z
    entry_dir = [tuple(int(x) for x in -m[:, 1]) for m in mats]  # local -Y

    def opp(a, b):
        return a[0] == -b[0] and a[1] == -b[1] and a[2] == -b[2]

    comp = np.zeros((n, n), dtype=bool)
    for a in range(n):
        for b in range(n):
            ea, xa, eb, xb = entry_dir[a], exit_dir[a], entry_dir[b], exit_dir[b]
            comp[a, b] = (opp(ea, eb) and opp(xa, xb)) or (opp(ea, xb) and opp(xa, eb))
    return np.array(mats), step.tolist(), exit_dir, entry_dir, comp.tolist()


ROTATIONS, _STEP, _EXIT, _ENTRY, _COMPLEMENTARY = _build_tables()
assert len(ROTATIONS) == 24


def _poses(angles) -> tuple[list[tuple[int, int, int]], list[int]]:
    """Cells and rotation indices per wedge (fast path, plain Python)."""
    r = 0
    p = (0, 0, 0)
    cells = [p]
    rots = [0]
    step, exit_dir = _STEP, _EXIT
    for a in angles:
        e = exit_dir[r]
        p = (p[0] + e[0], p[1] + e[1], p[2] + e[2])
        r = step[r][a & 3]
        cells.append(p)
        rots.append(r)
    return cells, rots


def forward_kinematics(angles) -> tuple[np.ndarray, np.ndarray]:
    """Integer cell centre (n, 3) and rotation matrix (n, 3, 3) per wedge.

    Wedge 0 sits at the origin with identity rotation. The rotation maps the
    wedge's local frame to the world frame (same as `rotation` in JS, which is
    the row-major flattening of these matrices).
    """
    cells, rots = _poses([int(a) for a in angles])
    return np.array(cells, dtype=np.int64), ROTATIONS[rots]


def _collisions(cells, rots, first_only=False):
    seen: dict = {}
    out = []
    comp = _COMPLEMENTARY
    for i, c in enumerate(cells):
        others = seen.get(c)
        if others is None:
            seen[c] = [i]
            continue
        ri = rots[i]
        for o in others:
            if not comp[rots[o]][ri]:
                if first_only:
                    return [(o, i)]
                out.append((o, i))
        others.append(i)
    return out


def find_collisions(angles) -> list[tuple[int, int]]:
    """All pairs (i, j), i < j, of wedges whose interiors overlap."""
    cells, rots = _poses([int(a) for a in angles])
    return sorted(_collisions(cells, rots))


def is_valid(angles) -> bool:
    cells, rots = _poses([int(a) for a in angles])
    return not _collisions(cells, rots, first_only=True)


def twist(angles, joint: int, direction: int) -> np.ndarray:
    nxt = np.array(angles, dtype=np.int64).copy()
    nxt[joint] = (nxt[joint] + direction) % 4
    return nxt


def valid_moves(angles) -> list[tuple[int, int]]:
    """All quarter-turn moves (joint, direction) with a valid end state.

    Only the end state is checked, not the sweep during the twist. Order is
    joint ascending, direction +1 before -1, as in JS.
    """
    return [m for m, ok in zip(ALL_MOVES(len(angles)), valid_move_mask(angles)) if ok]


def ALL_MOVES(num_joints: int) -> list[tuple[int, int]]:  # noqa: N802  (constant-like)
    return [(j, d) for j in range(num_joints) for d in (1, -1)]


def valid_move_mask(angles) -> np.ndarray:
    """Boolean mask over actions a = 2*joint + (0 for +1, 1 for -1).

    Reuses the unchanged prefix of the chain: a twist of joint j only moves
    wedges j+1.., so their cells are recomputed and checked against the cells
    of wedges 0..j and against each other.
    """
    angles = [int(a) for a in angles]
    n = len(angles)
    cells, rots = _poses(angles)
    step, exit_dir, comp = _STEP, _EXIT, _COMPLEMENTARY
    mask = np.zeros(2 * n, dtype=bool)
    # Occupancy of the fixed prefix, built up incrementally.
    prefix: dict = {}
    prefix_ok = True
    for j in range(n):
        c, r = cells[j], rots[j]
        lst = prefix.get(c)
        if lst is None:
            prefix[c] = [r]
        else:
            for o in lst:
                if not comp[o][r]:
                    prefix_ok = False
            lst.append(r)
        if not prefix_ok:
            break
        for k, d in enumerate((1, -1)):
            a = (angles[j] + d) & 3
            # Wedges j+1..n with the twisted joint.
            occ: dict = {}
            ok = True
            r2 = rots[j]
            p = cells[j]
            for jj in range(j, n):
                e = exit_dir[r2]
                p = (p[0] + e[0], p[1] + e[1], p[2] + e[2])
                r2 = step[r2][a if jj == j else angles[jj]]
                for lst2 in (prefix.get(p), occ.get(p)):
                    if lst2:
                        for o in lst2:
                            if not comp[o][r2]:
                                ok = False
                                break
                    if not ok:
                        break
                if not ok:
                    break
                occ.setdefault(p, []).append(r2)
            mask[2 * j + k] = ok
    return mask


def straight(num_wedges: int = NUM_WEDGES) -> np.ndarray:
    return np.zeros(num_wedges - 1, dtype=np.int64)


def angle_distance(a, b) -> int:
    """Sum of cyclic angle distances min(|d|, 4-|d|); ignores collisions."""
    d = np.abs(np.asarray(a) - np.asarray(b)) % 4
    return int(np.minimum(d, 4 - d).sum())
